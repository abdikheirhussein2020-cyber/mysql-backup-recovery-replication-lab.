-- ============================================================
-- MYSQL BACKUP AND RECOVERY COMMANDS
-- ============================================================

-- This file contains SQL commands used to verify the
-- database, binary logging, backup restoration, and recovery.

-- ============================================================
-- 1. DISPLAY AVAILABLE DATABASES
-- ============================================================

SHOW DATABASES;

-- ============================================================
-- 2. SELECT THE SCHOOL DATABASE
-- ============================================================

USE school;

-- ============================================================
-- 3. DISPLAY TABLES
-- ============================================================

SHOW TABLES;

-- ============================================================
-- 4. CHECK THE STUDENTS TABLE
-- ============================================================

SELECT * FROM students;

-- ============================================================
-- 5. CHECK STUDENTS TABLE STRUCTURE
-- ============================================================

DESCRIBE students;

-- ============================================================
-- 6. VERIFY BINARY LOGGING
-- ============================================================

SHOW VARIABLES LIKE 'log_bin';

-- ============================================================
-- 7. CHECK BINARY LOG FORMAT
-- ============================================================

SHOW VARIABLES LIKE 'binlog_format';

-- ============================================================
-- 8. DISPLAY AVAILABLE BINARY LOG FILES
-- ============================================================

SHOW BINARY LOGS;

-- ============================================================
-- 9. DISPLAY CURRENT BINARY LOG POSITION
-- ============================================================

SHOW MASTER STATUS;

-- ============================================================
-- 10. CREATE THE BACKUP VERIFICATION DATABASE
-- ============================================================

CREATE DATABASE IF NOT EXISTS bootcamp_check;

-- ============================================================
-- 11. VERIFY THE RESTORED DATABASE
-- ============================================================

USE bootcamp_check;

SHOW TABLES;

-- ============================================================
-- 12. VERIFY RESTORED STUDENT DATA
-- ============================================================

SELECT * FROM students;

-- ============================================================
-- 13. RETURN TO THE SCHOOL DATABASE
-- ============================================================

USE school;

-- ============================================================
-- 14. VERIFY STUDENT COUNT
-- ============================================================

SELECT COUNT(*) AS student_count
FROM students;

-- ============================================================
-- 15. VERIFY REPLICATION TEST TABLE
-- ============================================================

SHOW TABLES;

SELECT * FROM replication_test;

-- ============================================================
-- END OF BACKUP AND RECOVERY SQL
